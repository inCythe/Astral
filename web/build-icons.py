"""Fetches Lucide icon bodies and emits web/icons.js.

Only used when regenerating the icon set:  python web/build-icons.py
The generated file is committed so the playground works offline / from file://.
"""
import json
import re
import urllib.request

ICONS = [
    "search", "minus", "x", "chevron-down", "chevron-right", "move-diagonal-2",
    "sliders-horizontal", "type", "mouse-pointer-2", "columns-2", "git-branch",
    "message-square", "picture-in-picture-2", "settings", "toggle-left",
    "list-checks", "keyboard", "palette", "mouse-pointer-click", "text", "check",
    "pencil", "plus", "copy", "trash-2", "eye", "shield", "swords", "zap",
    "user", "layers", "save", "rotate-ccw", "square-check", "braces",
    "circle-dot", "gauge", "gamepad-2", "crosshair", "sparkles", "lock",
]

BASE = "https://unpkg.com/lucide-static@0.544.0/icons/{}.svg"


def body(name: str) -> str:
    raw = urllib.request.urlopen(BASE.format(name), timeout=20).read().decode("utf-8")
    inner = raw[raw.index(">", raw.index("<svg")) + 1: raw.rindex("</svg>")]
    inner = re.sub(r"\s+", " ", inner).strip()
    return inner


def main() -> None:
    out = {}
    for name in ICONS:
        try:
            out[name] = body(name)
        except Exception:
            print("skip", name)
    with open("web/icons.js", "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by web/build-icons.py from lucide-static 0.544.0 (ISC).\n")
        f.write("// Inner SVG markup for each icon; astral.js wraps it in <svg>.\n")
        f.write("window.LUCIDE_ICONS = ")
        f.write(json.dumps(out, indent=2))
        f.write(";\n")
    print("wrote", len(out), "icons")


if __name__ == "__main__":
    main()
